import { describe, it, expect } from 'vitest'
import { syncFuneralEndDate } from '../utils/funeralDateSync'

/**
 * 葬儀・告別式の開始日時を入れたとき、終了日時の日付を開始日に揃える。
 *
 * 告別式が日付を跨ぐ運用は無いが、終了日時は日付から入力する作りだったため、
 * 時刻だけ直して日付を直し忘れる誤入力が起きていた。
 * 本番データでも、終了が開始より前になっている案件が複数見つかっている。
 */

describe('終了日時の日付合わせ', () => {
    it('終了日時が未入力なら、開始と同じ日付の0時を置く', () => {
        expect(syncFuneralEndDate('2026-08-29T14:30', '')).toBe('2026-08-29T00:00')
    })

    it('終了日時が入っていれば、時刻は残して日付だけ合わせる', () => {
        // 担当者が入れた 16:00 を消さない
        expect(syncFuneralEndDate('2026-08-29T14:30', '2026-08-27T16:00')).toBe('2026-08-29T16:00')
    })

    it('開始を別の日に変えると、終了の日付も追従する', () => {
        expect(syncFuneralEndDate('2026-09-02T10:00', '2026-08-29T16:00')).toBe('2026-09-02T16:00')
    })

    it('開始が未入力なら終了には触れない', () => {
        // 開始を消しただけで終了が書き換わると、入力済みの値を失う
        expect(syncFuneralEndDate('', '2026-08-29T16:00')).toBe('2026-08-29T16:00')
    })

    it('開始・終了とも未入力なら未入力のまま', () => {
        expect(syncFuneralEndDate('', '')).toBe('')
    })

    it('終了に日付しか入っていない場合は0時を補う', () => {
        expect(syncFuneralEndDate('2026-08-29T14:30', '2026-08-27')).toBe('2026-08-29T00:00')
    })

    it('実際に起きていた誤入力の形を直せる', () => {
        // 本番の受付番号1029: 開始 07/25 14:30 / 終了 07/24 16:00（終了が開始より前）
        expect(syncFuneralEndDate('2026-07-25T14:30', '2026-07-24T16:00')).toBe('2026-07-25T16:00')
    })
})
